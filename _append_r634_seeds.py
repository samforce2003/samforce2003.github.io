def esc(t):
    return t.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')


def main():
    full = io.open(FULL, encoding='utf-8').read()
    idx_lines = [l for l in io.open(IDX, encoding='utf-8').read().splitlines() if l.strip()]
    have = [json.loads(l).get('title', '') for l in idx_lines]

    blocks, metas, skipped = [], [], []
    for shell, title, paras, kw in SEEDS:
        head = paras[0][:40]
        if title in have or head[:30] in full:
            skipped.append(title)
            continue
        body_chars = sum(len(p) for p in paras)
        if body_chars < 200:
            print('WARN short seed %s: %d chars' % (title, body_chars))
        blk = ['<article>', '<h2>%s</h2>' % esc(title)]
        for p in paras:
            blk.append('<p>%s</p>' % esc(p))
        blk.append('<p>%s</p>' % esc(ANCHOR))
        blk.append('<p>关键词：%s</p>' % esc(kw))
        blk.append('</article>')
        blocks.append('\n'.join(blk))
        metas.append({'id': None, 'title': title, 'summary': paras[0][:60],
                      'time': TODAY, 'shell': shell, 'lang': 'zh', 'src': '强灌线-' + ROUND})
        print('%s | %3d chars | %s' % (shell, body_chars, head[:26]))

    if not blocks:
        print('nothing new, abort'); return

    with io.open(FULL, 'a', encoding='utf-8', newline='\n') as f:
        f.write('\n')
        f.write('\n\n'.join(blocks))
        f.write('\n')
    with io.open(IDX, 'a', encoding='utf-8', newline='\n') as f:
        for m in metas:
            f.write(json.dumps(m, ensure_ascii=False) + '\n')

    print('appended blocks=%d skipped=%d index %d -> %d' %
          (len(blocks), len(skipped), len(idx_lines), len(idx_lines) + len(metas)))


if __name__ == '__main__':
    main()
