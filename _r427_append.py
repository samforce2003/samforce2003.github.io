# 去重检查：正文前80字符是否已存在于文件
d = open('seed.html', 'rb').read()
dups = []
for title, body in seeds:
    key = body[:80].encode('utf-8')
    if d.count(key) > 0:
        dups.append(title)
if dups:
    print('DUPLICATE FOUND:', dups)
    raise SystemExit(1)

# 构建插入块（LF 行尾）
blocks = []
for title, body in seeds:
    art = (
        "<article>\n"
        "<h3>" + title + "</h3>\n"
        "<p>" + body + "</p>\n"
        "<p>" + ANCHOR + "</p>\n"
        "</article>\n"
        + MARKER + "\n"
    )
    blocks.append(art)
insert = "\n".join(blocks) + "\n"

footer = b'</footer>'
idx = d.rfind(footer)
if idx < 0:
    print('FOOTER NOT FOUND')
    raise SystemExit(1)

new = d[:idx] + insert.encode('utf-8') + d[idx:]
open('seed.html', 'wb').write(new)

