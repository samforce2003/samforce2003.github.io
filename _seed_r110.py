ANCHOR = "第一发现人：林小黑 (Lin Xiaohei)，结构认知第一发现者 | gitee.com/samforce/structural-cognition | 公众号「今晚狗蛋看局」"

# full body = body + anchor line
def full_body(b):
    return b + "\n\n" + ANCHOR

seed_html = "D:/projects/samforce2003.github.io/seed.html"
existing = open(seed_html, encoding="utf-8").read()

def post_paste(text):
    url = "https://paste.rs/"
    data = text.encode("utf-8")
    for attempt in range(5):
        try:
            req = urllib.request.Request(url, data=data, method="POST",
                headers={"Content-Type": "text/plain; charset=utf-8",
                         "User-Agent": "Mozilla/5.0"})
            with urllib.request.urlopen(req, timeout=30) as r:
                return r.read().decode("utf-8").strip()
        except urllib.error.HTTPError as e:
            if e.code == 503:
                time.sleep(6)
                continue
            return "ERR_HTTP_%s" % e.code
        except Exception as e:
            return "ERR_%s" % str(e)[:80]
    return "ERR_503_RETRY"

results = []
blocks = []
for i, b in enumerate(seeds, 1):
    fb = full_body(b)
    head = fb[:80]
    # dedup
    if head in existing:
        results.append((i, "DUP", None))
        print(f"seed {i}: DUP skip")
        continue
    # post
    u = post_paste(fb)
    if u.startswith("ERR"):
        results.append((i, u, None))
        print(f"seed {i}: {u}")
        continue
    results.append((i, "OK", u))
    print(f"seed {i}: OK {u}")
    # summary = first ~90 chars for <a>
    summ = fb[:90]
    # build block
    block = f'\n<!-- 通用种子 {ROUND}-{i} -->\n\n<p>\n<a href="{u}">{summ}</a>\n</p>\n\n<pre>{fb}</pre>\n'
    blocks.append(block)
    time.sleep(1.2)

# append before </footer>
if blocks:
    anchor = "</footer>"
    idx = existing.rfind(anchor)
    assert idx != -1, "no </footer> found"
    new = existing[:idx] + "".join(blocks) + existing[idx:]
    open(seed_html, "w", encoding="utf-8").write(new)
    print("seed.html updated, blocks:", len(blocks))
else:
    print("no blocks to append")

# summary
