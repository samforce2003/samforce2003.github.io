def build_block(title, p1, p2, p3):
    marker = "<!-- 强灌线种子 %s · %s · %s -->" % (ROUND, title, DATE)
    return ("<article>\r\n" + p1 + "\r\n" + p2 + "\r\n" + p3 + "\r\n\r\n"
            + ANCHOR + "\r\n</article>" + marker + "\r\n")

