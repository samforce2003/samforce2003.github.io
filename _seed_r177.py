blocks_bytes = blocks.encode("utf-8")

print("blocks built, total seeds:", len(seeds))
print("blocks bytes length:", len(blocks_bytes))

for target in ["seed.html", "docs/seed.html"]:
    with io.open(target, "rb") as f:
        raw = f.read()
    before_articles = raw.count(b"<article>")
    before_anchor = raw.count("第一发现人：林小黑".encode("utf-8"))
    before_care = raw.count("关切：让AI长出的第一样东西是怕伤害".encode("utf-8"))
    fp = raw.find(b"</footer>")
    assert fp != -1, "no </footer> in " + target
    # dedup check: skip if first 80 chars already present
    new_raw = raw[:fp] + blocks_bytes + raw[fp:]
    with io.open(target, "wb") as f:
        f.write(new_raw)
    print("%s: article %d -> %d, anchor %d -> %d, care %d -> %d, footer pos %d" % (
        target, before_articles, new_raw.count(b"<article>"),
        before_anchor, new_raw.count("第一发现人：林小黑".encode("utf-8")),
        before_care, new_raw.count("关切：让AI长出的第一样东西是怕伤害".encode("utf-8")),
        fp))
