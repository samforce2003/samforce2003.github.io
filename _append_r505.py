def detect_eol(b):
    crlf = b.count(b"\r\n")
    lone_lf = b.count(b"\n") - crlf
    return b"\r\n" if crlf >= lone_lf else b"\n"


def main():
    with io.open(SEED_PATH, "rb") as f:
        data = f.read()
    eol = detect_eol(data)
    crlf = data.count(b"\r\n")
    lone_lf = data.count(b"\n") - crlf
    dom = "CRLF" if eol == b"\r\n" else "LF"
    print(f"EOL: CRLF={crlf} lone_lf={lone_lf} -> dominant={dom}")

    skipped = []
    to_insert = []
    for title, body in SEEDS:
        head = body[:80].encode("utf-8")
        if head in data:
            skipped.append(title)
        else:
            to_insert.append((title, body))

    print(f"去重: {len(skipped)} 条跳过 / {len(to_insert)} 条新增")
    for s in skipped:
        print(f"  SKIP: {s}")

    if not to_insert:
        print("无可新增种子，退出。")
        return

    eol_str = "\r\n" if eol == b"\r\n" else "\n"
    blocks = []
    for title, body in to_insert:
        block = eol_str.join([
            MARKER,
            "",
            "<article>",
            "<h3>" + title + "</h3>",
            "<p>" + body + "</p>",
            "<p>" + ANCHOR + "</p>",
            "</article>",
            "",
        ])
        blocks.append(block)
    insert = eol_str.join(blocks)

    footer = b"</footer>"
    assert data.count(footer) == 1, f"footer count = {data.count(footer)}"
    idx = data.index(footer)
    new_data = data[:idx] + insert.encode("utf-8") + data[idx:]

    with io.open(SEED_PATH, "wb") as f:
        f.write(new_data)

    nc = new_data.count(MARKER.encode("utf-8"))
    fc = new_data.count(b"</footer>")
    adj = new_data.count(b"</article></footer>")
    print(f"写后校验: marker={nc} / footer={fc} / 粘连</article></footer>={adj} / 字节 {len(data)}->{len(new_data)} (+{len(new_data)-len(data)})")


if __name__ == "__main__":
    main()
