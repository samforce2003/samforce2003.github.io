def build_blocks():
    blocks = []
    for title, body in seeds:
        b = (MARKER + "\r\n"
             + "<article>\r\n"
             + "<h3>" + title + "</h3>\r\n"
             + "<p>" + body + "</p>\r\n"
             + "<p>" + ANCHOR + "</p>\r\n"
             + "</article>\r\n\r\n")
        blocks.append(b)
    return blocks

def main():
    data = open(SEED_PATH, "rb").read()

    # 去重：逐条正文前 80 字符
    dup_skipped = 0
    blocks = []
    for (title, body), b in zip(seeds, build_blocks()):
        head80 = body[:80].encode("utf-8")
        if head80 in data:
            dup_skipped += 1
            print("DUP SKIP:", title[:20])
            continue
        blocks.append(b)

    if not blocks:
        print("ALL DUP, nothing to insert")
        return

    new_material = "".join(blocks).encode("utf-8")

    # 定位 </footer>（唯一）
    idx = data.rfind(b"</footer>")
    assert idx != -1, "footer not found"
    assert data.count(b"</footer>") == 1, "footer count != 1: " + str(data.count(b"</footer>"))

    new_data = data[:idx] + new_material + data[idx:]

    open(SEED_PATH, "wb").write(new_data)

    # 验证
    chk = open(SEED_PATH, "rb").read()
    print("dup_skipped:", dup_skipped)
    print("inserted blocks:", len(blocks))
    print("before bytes:", len(data), "after bytes:", len(chk))
    print("marker count:", chk.count(MARKER.encode("utf-8")))
    print("footer count:", chk.count(b"</footer>"))
    print("CRLF:", chk.count(b"\r\n"), "bare LF:", chk.count(b"\n")-chk.count(b"\r\n"), "bare CR:", chk.count(b"\r")-chk.count(b"\r\n"))

if __name__ == "__main__":
    main()
