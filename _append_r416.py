def build_blocks(crlf=True):
    nl = "\r\n" if crlf else "\n"
    out = []
    for title, body in SEEDS:
        out.append("<!-- 强灌线种子 %s -->%s<article>%s<h3>%s</h3>%s<p>%s</p>%s<p>%s</p>%s</article>%s%s" % (
            ROUND, nl, nl, title, nl, body, nl, ANCHOR, nl, nl, nl))
    return nl.join(out)  # 用 join 拼接各块（块间已带 nl 结尾，这里不再重复）

def main():
    import io
    d = open(SEED_HTML, 'rb').read()

    # 去重检查：正文前80字符是否已存在
    for title, body in SEEDS:
        k = body[:80].encode('utf-8')
        c = d.count(k)
        if c > 0:
            print("DUP FOUND, aborting: %s ... count=%d" % (title[:20], c))
            return 1

    # 轮号 marker 去重
    if MARKER.encode('utf-8') in d:
        print("ROUND MARKER already present, aborting:", MARKER)
        return 1

    footer = d.rfind(b'</footer>')
    if footer == -1:
        print("NO </footer> found, aborting")
        return 1
    if d.count(b'</footer>') != 1:
        print("footer count != 1:", d.count(b'</footer>'))
        return 1

    block_bytes = build_blocks(crlf=True).encode('utf-8')
    new = d[:footer] + block_bytes + d[footer:]

    open(SEED_HTML, 'wb').write(new)

    # 验证
    d2 = open(SEED_HTML, 'rb').read()
    print("before bytes:", len(d), "after bytes:", len(d2), "delta:", len(d2)-len(d))
    print("footer count after:", d2.count(b'</footer>'))
    print("marker count after:", d2.count(MARKER.encode('utf-8')))
    print("CRLF count after:", d2.count(b'\r\n'), "bare LF:", d2.count(b'\n')-d2.count(b'\r\n'))
    print("OK")
    return 0

if __name__ == '__main__':
    sys.exit(main())
