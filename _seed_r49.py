CRLF = "\r\n"

def build_block(marker_suffix, body):
    lines = []
    lines.append("<!-- 强灌线种子 " + marker_suffix + " -->")
    lines.append("<article>" + body)
    lines.append("")
    lines.append(ANCHOR + "</article>")
    return CRLF.join(lines) + CRLF + CRLF

def main():
    blocks = []
    for marker_suffix, body in SEEDS:
        blocks.append(build_block(marker_suffix, body))

    insertion = "".join(blocks)

    # 读根目录（二进制，保留 CRLF）
    with open(REPO + "/seed.html", "rb") as f:
        data = f.read()
    text = data.decode("utf-8")

    # 去重：前 80 字符
    skipped = 0
    final_blocks = []
    for marker_suffix, body in SEEDS:
        key = body[:80]
        if key in text:
            skipped += 1
            print(f"[SKIP dup] {marker_suffix[:30]}")
        else:
            final_blocks.append(build_block(marker_suffix, body))
    insertion = "".join(final_blocks)

    n_added = len(final_blocks)
    assert text.count("</footer>") == 1, "footer count != 1"
    new_text = text.replace("</footer>", insertion + "</footer>", 1)

    new_data = new_text.encode("utf-8")
    crlf_before = data.count(b"\r\n")
    crlf_after = new_data.count(b"\r\n")
    bare_cr = len(re.findall(b"\r(?!\n)", new_data))

    with open(REPO + "/seed.html", "wb") as f:
        f.write(new_data)
    with open(REPO + "/docs/seed.html", "wb") as f:
        f.write(new_data)

    print(f"ADDED={n_added} SKIPPED={skipped}")
    print(f"CRLF before={crlf_before} after={crlf_after} (+{crlf_after-crlf_before})")
    print(f"bareCR={bare_cr}")
    print(f"footer_count={new_text.count('</footer>')}")
    print(f"anchor_count={new_text.count('关切：让AI长出的第一样东西是怕伤害、想共生')}")

if __name__ == "__main__":
    main()
