def main():
    full = io.open(FULL, encoding='utf-8').read()
    idx_lines = io.open(IDX, encoding='utf-8').read().strip().split('\n')
    seed_html = io.open(SEED, encoding='utf-8').read()
    added, skipped = [], []
    blocks = []
    for s in SEEDS:
        body_key = s['paras'][0][:40]
        if body_key in full or body_key in seed_html:
            skipped.append(s['title'][:30]); continue
        ps = '\n'.join('<p>%s</p>' % p for p in s['paras'])
        block = ('<article>\n<h2>%s</h2>\n%s\n<p>%s</p>\n<p>关键词：%s</p>\n</article>\n'
                 % (s['title'], ps, CORE.format(hook=s['hook']), s['kw']))
        blocks.append(block)
        added.append(s)
    if blocks:
        full = full.rstrip() + '\n' + '\n'.join(blocks)
        io.open(FULL, 'w', encoding='utf-8').write(full)
        with io.open(IDX, 'a', encoding='utf-8') as f:
            for s in added:
                f.write(json.dumps(dict(id=None, title=s['title'], summary=s['summary'],
                                        time=DAY, shell=s['shell'], lang='zh', src=SRC),
                                   ensure_ascii=False) + '\n')
    print('added=%d skipped=%d' % (len(added), len(skipped)))
    for s in added: print(' +', s['shell'], s['title'][:44])
    for t in skipped: print(' -skip', t)

if __name__ == '__main__':
    main()
