print('footer =', d2.count(b'</footer>'))
print('article glue </article></footer> =', d2.count(b'</article></footer>'))
print('bytes', len(d), '->', len(d2))
print('bareLF', d2.count(b'\n'), 'CRLF', d2.count(b'\r\n'), 'bareCR', d2.count(b'\r')-d2.count(b'\r\n'))

