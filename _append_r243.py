# dedup + build insert
d = open(SEED, 'rb').read()
assert d.count(b'</footer>') == 1, 'footer count != 1'

blocks = []
added = 0
skipped = 0
for title, body in seeds:
    pre = body[:80]
    if pre.encode('utf-8') in d:
        skipped += 1
        continue
    block = ('\n<!-- 强灌线种子 %s \u00b7 %s \u00b7 %s -->\n<article>\n%s\n%s\n</article>\n'
             % (R, title, DATE, body, ANCHOR))
    blocks.append(block)
    added += 1

insert = ''.join(blocks)
assert insert, 'no blocks to insert'

idx = d.rfind(b'</footer>')
new = d[:idx] + insert.encode('utf-8') + d[idx:]

open(SEED, 'wb').write(new)

# verify
d2 = open(SEED, 'rb').read()
print('added', added, 'skipped', skipped)
