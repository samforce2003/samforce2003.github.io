p = "D:/projects/samforce2003.github.io/seed.html"
data = open(p, "rb").read()
txt = data.decode("utf-8")

# 去重检查
skip = 0
for title, body in seeds:
    key = body[:40]
    if key in txt:
        skip += 1
        print("DUP skip:", title[:20])
print("去重跳过:", skip)

# 构造块
blocks = []
for title, body in seeds:
    if body[:40] in txt:
        continue
    b = ("<!-- " + MARKER + " -->\n"
         "<article>\n"
         "<h3>" + title + "</h3>\n"
         "<p>" + body + "</p>\n"
         "<p>" + ANCHOR + "</p>\n"
         "</article>\n")
    blocks.append(b)

print("新增正文条数:", len(blocks))
if not blocks:
    print("无新增，退出")
    sys.exit(0)

inject = "".join(blocks)
footer = "</footer>"
i = txt.rfind(footer)
assert i != -1, "footer not found"
newtxt = txt[:i] + inject + txt[i:]

nb = newtxt.encode("utf-8")
open(p, "wb").write(nb)
# 双副本同步
p2 = "D:/projects/samforce2003.github.io/docs/seed.html"
open(p2, "wb").write(nb)

