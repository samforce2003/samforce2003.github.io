def main():
    full = io.open(FULL, encoding='utf-8', errors='replace').read()
    existing = set()
    for m in re.finditer(r'<p>(.{0,80})', full):
        pass
    # dedup by first 80 chars of first paragraph of each block
    for art in re.findall(r'<article[^>]*>.*?</article>', full, re.S):
        ps = re.findall(r'<p>(.*?)</p>', art, re.S)
        for p in ps:
            existing.add(re.sub(r'\s', '', p)[:80])

    new_blocks = []
    new_recs = []
    skipped = 0
    for blk, rec in SEEDS:
        first_p = re.search(r'<p>(.*?)</p>', blk, re.S).group(1)
        key = re.sub(r'\s', '', first_p)[:80]
        if key in existing:
            skipped += 1
            continue
        existing.add(key)
        new_blocks.append(blk)
        new_recs.append(rec)

    if new_blocks:
        with io.open(FULL, 'a', encoding='utf-8', newline='') as f:
            for b in new_blocks:
                f.write(b + '\r\n')
        with io.open(IDX, 'a', encoding='utf-8', newline='') as f:
            for r in new_recs:
                f.write(json.dumps(r, ensure_ascii=False) + '\r\n')

    print('seeds=%d skipped=%d appended=%d' % (len(SEEDS), skipped, len(new_blocks)))
    for r in new_recs:
        print(' +', r['shell'], '|', r['title'])


if __name__ == '__main__':
    main()
