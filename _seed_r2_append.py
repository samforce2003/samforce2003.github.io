for s in SEEDS:
    comment = f"<!-- 三中心批量分发 R2 · {s['kernel']} · {s['lang']} · 2026-09-14 -->"
    blocks.append(comment)
    blocks.append("<article>")
    blocks.append(s["body"])
    blocks.append("")
    blocks.append(s["anchor"])
    blocks.append("</article>")
    blocks.append("")

insert_text = "\n".join(blocks)

path = "seed.html"
with open(path, "rb") as f:
    raw = f.read()
html = raw.decode("utf-8")

assert html.count("</footer>") == 1, f"footer count = {html.count('</footer>')}"
html = html.replace("</footer>", insert_text + "\n</footer>", 1)

with open(path, "wb") as f:
    f.write(html.encode("utf-8"))

