def block(title, body, kw):
    ps = u''.join(u'<p>%s</p>\n' % p.strip() for p in body.split('\n') if p.strip())
    return (u'<article>\n<h2>%s</h2>\n%s<p>%s</p>\n<p>%s</p>\n</article>\n\n'
            % (title, ps, ANCHOR, kw))

def main():
    full = io.open(FULL, encoding='utf-8').read()
    n_idx = sum(1 for l in io.open(INDEX, encoding='utf-8') if l.strip())
    print('before: entries=%d full_bytes=%d' % (n_idx, len(full.encode('utf-8'))))

    blocks, idx = [], []
    skipped = 0
    nid = n_idx
    for title, shell, kw, body, summary in SEEDS:
        head80 = body.replace('\n', '')[:80]
        # 去重：正文前 80 字（去换行）是否已在全量正文里
        flat = full.replace('\r', '')
        if head80 in flat.replace('\n', ''):
            print('SKIP dup: %s' % title); skipped += 1; continue
        nid += 1
        blocks.append(block(title, body, kw))
        idx.append(json.dumps({'id': nid, 'title': title, 'summary': summary,
                               'time': DAY, 'shell': shell, 'lang': 'zh', 'src': SRC},
                              ensure_ascii=False))

    if blocks:
        with io.open(FULL, 'a', encoding='utf-8') as f:
            f.write(u''.join(blocks))
        with io.open(INDEX, 'a', encoding='utf-8') as f:
            f.write(u'\n'.join(idx) + u'\n')

    full2 = io.open(FULL, encoding='utf-8').read()
    n2 = sum(1 for l in io.open(INDEX, encoding='utf-8') if l.strip())
    print('after:  entries=%d full_bytes=%d added=%d skipped=%d ids=%s'
          % (n2, len(full2.encode('utf-8')), len(blocks), skipped,
             ('%d-%d' % (nid - len(blocks) + 1, nid)) if blocks else 'none'))

if __name__ == '__main__':
    main()
