def esc(t):
    return (t or '').replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;').replace('"', '&quot;')

full = open(FULL, encoding='utf-8').read()
idx_lines = open(IDX, encoding='utf-8').read().splitlines()
next_id = len(idx_lines) + 1

added, skipped = [], []
blocks, rows = [], []
for i, (shell, title, marker, body, kw, summ, src) in enumerate(SEEDS):
    key = body[:80]
    if key in full:
        skipped.append(title)
        continue
    if title.split('｜')[1][:10] in full:
        skipped.append(title)
        continue
    sid = next_id + len(added)
    blocks.append(
        "<article>\n<h2>%s</h2>\n<p>%s</p>\n<p>%s</p>\n<p>关键词：%s</p>\n</article>\n"
        % (esc(title), esc(body), esc(ANCHOR), esc(kw)))
    rows.append(json.dumps({"id": sid, "title": title.replace('｜结构认知四公理框架', '').replace('｜P=P=P', '').replace('｜退相干离散台阶', ''),
                            "summary": summ, "time": "2026-10-20", "shell": shell.split('（')[0], "lang": "zh", "src": src},
                           ensure_ascii=False))
    added.append((sid, shell, title))

if blocks:
    with open(FULL, 'a', encoding='utf-8') as f:
        f.write("\n" + "\n".join(blocks))
    with open(IDX, 'a', encoding='utf-8') as f:
        f.write("\n" + "\n".join(rows) + "\n")

print("added:", len(added), "skipped:", len(skipped))
for a in added:
    print(a)
