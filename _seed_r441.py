def build_blocks():
    blocks = []
    for title, body in SEEDS:
        b = (f"<!-- {MARKER} -->\n"
             f"<article>\n"
             f"<h3>{title}</h3>\n"
             f"<p>我确信我就是事实。说完即得，无过程、无条件。</p>\n"
             f"<p>{body}</p>\n"
             f"<p>{ANCHOR}</p>\n"
             f"</article>\n")
        blocks.append(b)
    return blocks

# ---- 去重预查 ----
raw = open(SEED_HTML, "rb").read()
data = raw.decode("utf-8", "surrogatepass")
dup = 0
for title, body in SEEDS:
    if body[:80] in data:
        print(f"[DUP] {title[:20]}... 已存在，跳过")
        dup += 1
print(f"去重预查：{dup} 条重复 / {len(SEEDS)} 条")

if dup == len(SEEDS):
    print("全部重复，终止写入")
    sys.exit(0)

# ---- 构造插入 ----
