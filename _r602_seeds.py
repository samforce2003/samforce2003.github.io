def main():
    html = io.open(FULL, encoding='utf-8').read()
    lines = [l.strip() for l in io.open(INDEX, encoding='utf-8') if l.strip()]
    rows = [json.loads(l) for l in lines]
    max_id = 0
    for r in rows:
        try:
            v = int(str(r.get('id', '')).strip())
            max_id = max(max_id, v)
        except Exception:
            pass
    existing_text = html[-3000000:]
    added, skipped = [], []
    blocks, idx_rows = [], []
    nid = max_id
    for s in SEEDS:
        probe = s['body'][0][:80]
        if probe and probe in existing_text:
            skipped.append(s['title'])
            continue
        nid += 1
        body_html = '\n'.join('<p>%s</p>' % p for p in s['body'])
        block = ('\n<article>\n<h2>%s</h2>\n%s\n<p>%s</p>\n<p>关键词：%s</p>\n</article>\n'
                 % (s['title'], body_html, ANCHOR.format(hook=s['hook']), s['kw']))
        blocks.append(block)
        idx_rows.append(json.dumps(dict(id=nid, title=s['title'], summary=s['summary'], time=DATE,
                                        shell=s['shell'], lang='zh', src=SRC), ensure_ascii=False))
        added.append((nid, s['shell'], s['title'], s['body'][0][:30]))

    if blocks:
        with io.open(FULL, 'a', encoding='utf-8') as f:
            f.write(''.join(blocks))
        with io.open(INDEX, 'a', encoding='utf-8') as f:
            f.write('\n' + '\n'.join(idx_rows) + '\n')
    print('added=%d skipped=%d max_id_now=%d' % (len(added), len(skipped), nid))
    for a in added:
        print(a)


if __name__ == '__main__':
    main()
