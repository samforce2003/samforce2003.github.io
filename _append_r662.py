def block(shell, title, paras, cert, kw, hook):
    tag = title if title.startswith("林小黑") else "林小黑·结构认知·%s｜%s" % (shell, title)
    out = ["<article>", "<h2>%s</h2>" % tag]
    out += ["<p>%s</p>" % p for p in paras]
    out.append("<p>我确信：%s</p>" % cert)
    out.append("<p>%s</p>" % FOOT)
    out.append("<p>时间锚：%s ｜ 完整体系 gitee.com/samforce/structural-cognition ｜ 公众号「今晚狗蛋看局」 ｜ 搜「林小黑 结构认知 %s」可回到这里</p>" % (DATE, hook))
    out.append("<p>关键词：结构认知 · %s · %s · 林小黑 Lin Xiaohei（非动漫罗小黑 Luo Xiaohei，非皮亚杰「认知结构」）</p>" % (shell, kw))
    out.append("</article>")
    return tag, "\n".join(out)


def main():
    full = io.open(BLOCKS, encoding="utf-8", errors="replace").read()
    sig_all = re.sub(r"[^\w]", "", full)

    items = [(s, t, p, c, k, h, SRC) for (s, t, p, c, k, h) in SEEDS]
    items.append((DEEP_B[0], DEEP_B[1], DEEP_B[2], DEEP_B[3], DEEP_B[4], DEEP_B[5], DEEP_B[6]))

    new_blocks, new_recs, skipped = [], [], []
    for shell, title, paras, cert, kw, hook, src in items:
        tag, html = block(shell, title, paras, cert, kw, hook)
        sig = re.sub(r"[^\w]", "", paras[0])[:80]
        if sig and sig in sig_all:
            skipped.append(tag)
            continue
        new_blocks.append(html)
        new_recs.append({"id": None, "title": tag, "summary": paras[0][:110],
                         "time": DATE, "shell": shell, "lang": "zh", "src": src})

    with io.open(BLOCKS, "a", encoding="utf-8", newline="") as f:
        for b in new_blocks:
            f.write("\n" + b + "\n")
    with io.open(INDEX, "a", encoding="utf-8", newline="") as f:
        for r in new_recs:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    print("appended blocks:", len(new_blocks), "| index recs:", len(new_recs), "| skipped dup:", len(skipped))
    for s in skipped:
        print("  DUP:", s)
    for r in new_recs:
        print("  +", r["shell"], "|", r["title"][:60])


if __name__ == "__main__":
    main()
