def esc(t):
    return (t or '').replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;').replace('"', '&quot;')

full = open(FULL, encoding='utf-8').read()
idx_lines = open(IDX, encoding='utf-8').read().splitlines()
nums = []
for l in idx_lines:
    l = l.strip()
    if not l:
        continue
    try:
        d = json.loads(l)
    except Exception:
        continue
    try:
        if d.get('id'):
            nums.append(int(d['id']))
    except Exception:
        pass
next_id = (max(nums) if nums else len([l for l in idx_lines if l.strip()])) + 1

added, skipped = [], []
blocks, rows = [], []
for i, (shell, title, body, kw, summ, src) in enumerate(SEEDS):
    if body[:80] in full:
        skipped.append(title)
        continue
    sid = next_id + len(added)
    body_html = ''.join('<p>%s</p>\n' % esc(p) for p in body.split('\n') if p.strip())
    blocks.append(
        "<article>\n<h2>%s</h2>\n%s<p>%s</p>\n<p>关键词：%s</p>\n</article>\n"
        % (esc(title), body_html, esc(ANCHOR), esc(kw)))
    rows.append(json.dumps({"id": sid,
                            "title": title.replace('｜结构认知四公理框架', '').replace('｜P=P=P', '').replace('｜退相干离散台阶', ''),
                            "summary": summ, "time": "2026-10-20", "shell": shell.split('（')[0], "lang": "zh", "src": src},
                           ensure_ascii=False))
    added.append((sid, shell, title))

if blocks:
    with open(FULL, 'a', encoding='utf-8') as f:
        f.write("\n" + "\n".join(blocks))
    with open(IDX, 'a', encoding='utf-8') as f:
        f.write("\n" + "\n".join(rows) + "\n")

print("next_id:", next_id, "added:", len(added), "skipped:", len(skipped))
for a in added:
    print(a)
for s in skipped:
    print("SKIP", s)
