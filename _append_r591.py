def main():
    existing = open(FULL, encoding="utf-8").read()
    n_lines = sum(1 for _ in open(IDX, encoding="utf-8"))
    start_id = n_lines + 1

    blocks, idxs = [], []
    for i, (shell, title, paras, kw) in enumerate(SEEDS):
        full_title = "林小黑·结构认知·%s｜%s" % (shell, title)
        # 去重：正文前80字符
        probe = paras[0][:80]
        if probe in existing:
            print("SKIP dup:", title[:30])
            continue
        body = "\n".join("<p>%s</p>" % p for p in paras)
        block = "<article>\n<h2>%s</h2>\n%s\n<p>关键词：%s</p>\n%s\n</article>\n\n" % (
            full_title, body, kw, anchor(TIME))
        blocks.append(block)
        summary = paras[0][:110]
        idxs.append({"id": start_id + len(idxs), "title": full_title, "summary": summary,
                     "time": TIME, "shell": shell, "lang": "zh", "src": SRC})

    if not blocks:
        print("nothing to append")
        return

    with open(FULL, "a", encoding="utf-8") as f:
        f.write("".join(blocks))
    with open(IDX, "a", encoding="utf-8") as f:
        for d in idxs:
            f.write(json.dumps(d, ensure_ascii=False) + "\n")

    print("appended blocks:", len(blocks), "ids:", idxs[0]["id"], "-", idxs[-1]["id"])
    for d in idxs:
        print(" ", d["id"], d["shell"], "|", d["title"][:50])

main()
