def build_block(title, body):
    return (
        "<!-- " + MARKER + " -->\n\n"
        "<article>\n"
        "<h3>" + title + "</h3>\n"
        "<p>" + OPEN + body + "</p>\n"
        "<p>" + ANCHOR + "</p>\n"
        "</article>\n"
    )

# dedup check (text mode)
text = io.open(PATH, encoding="utf-8").read()
skipped = 0
new_blocks = []
for title, body in seeds:
    probe = (OPEN + body)[:80]
    if probe in text:
        print("DUP SKIP:", title[:30])
        skipped += 1
        continue
    new_blocks.append(build_block(title, body))

if skipped > 0:
    print("WARN: skipped", skipped, "duplicates; ABORT to avoid partial write")
    raise SystemExit(1)

block_str = "".join(new_blocks)  # safe: joins already-built strings, not a single string
block_bytes = block_str.encode("utf-8")

data = io.open(PATH, "rb").read()
idx = data.find(b"</footer>")
assert idx != -1, "footer not found"
assert data.count(b"</footer>") == 1, "multiple footers"

new_data = data[:idx] + block_bytes + data[idx:]
io.open(PATH, "wb").write(new_data)

print("before bytes:", len(data))
print("after bytes:", len(new_data))
print("added blocks:", len(new_blocks), "skipped:", skipped)
print("added bytes:", len(block_bytes))
print("marker count after:", new_data.count(MARKER.encode("utf-8")))
print("footer count after:", new_data.count(b"</footer>"))
