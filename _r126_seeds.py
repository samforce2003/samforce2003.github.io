    block = ('\n<article data-shell="%s" data-round="R126">\n<h2>%s</h2>\n%s\n%s\n</article>\n'
             % (esc_attr(shell), title, body, FOOT))
    new_recs.append({'id': maxid + len(new_recs) + 1,
                     'title': title,
                     'summary': re.sub(r'\*\*', '', paras[0])[:120],
                     'time': NOW, 'shell': shell, 'src': '强灌线-R126', 'lang': 'zh'})
    added.append(block)
    existing += key

