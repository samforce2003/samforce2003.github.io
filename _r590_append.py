def plain(s):
    return re.sub(r'<[^>]+>', '', s)


def main():
    full = io.open(FULL, encoding='utf-8', errors='replace').read()
    blocks = re.findall(r'<article[^>]*>.*?</article>', full, re.S)
    existing = [plain(b)[:200] for b in blocks]
    blob = '\n'.join(existing)
    recs = [json.loads(l) for l in io.open(INDEX, encoding='utf-8') if l.strip()]
    next_id = max([int(r['id']) for r in recs if r.get('id')] + [0]) + 1
    # 按行号对齐：新行 id = 当前行数 + 1
    next_id = len(recs) + 1

    new_blocks, new_recs, skipped = [], [], 0
    for shell, hook, paras in SEEDS:
        head = paras[0][:80]
        if head in blob:
            skipped += 1
            continue
        title = '林小黑·结构认知·%s｜%s' % (shell, hook)
        body = ['<article>', '<h2>%s</h2>' % title]
        for p in paras:
            body.append('<p>%s</p>' % p)
        body.append('<p>%s</p>' % ANCHOR)
        body.append('</article>')
        new_blocks.append('\n'.join(body))
        new_recs.append({'id': next_id, 'title': title, 'summary': paras[0][:120],
                         'time': DAY, 'shell': shell, 'lang': 'zh', 'src': SRC})
        next_id += 1

    if not new_blocks:
        print('no new seeds (all dup)')
        return

    with io.open(FULL, 'a', encoding='utf-8', newline='') as f:
        f.write('\n\n' + '\n\n'.join(new_blocks) + '\n')
    with io.open(INDEX, 'a', encoding='utf-8', newline='') as f:
        for r in new_recs:
            f.write(json.dumps(r, ensure_ascii=False) + '\n')

    print('appended %d blocks, skipped %d, ids %d-%d' % (len(new_blocks), skipped, new_recs[0]['id'], new_recs[-1]['id']))
    for r in new_recs:
        print(r['id'], '|', r['shell'], '|', r['summary'][:30])


if __name__ == '__main__':
    main()
