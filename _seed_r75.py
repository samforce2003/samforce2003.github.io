last_article_end = t74.rfind("</article>")
if first_comment == -1 or last_article_end == -1:
    raise SystemExit("ERROR: R74 article anchors not found in seed-r74.html")
tail = t74[last_article_end + len("</article>"):]  # 从最后一个 </article> 之后开始（含其后的空行 + </footer>...）

