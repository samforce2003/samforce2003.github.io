CRLF = "\r\n"

def build_block(idx, title, body):
    comment = "<!-- 强灌线种子 %s-%d · %s · %s -->" % (ROUND, idx, title, DATE)
    return CRLF.join([
        comment,
        "<article>",
        body,
        "",
        ANCHOR,
        "</article>",
    ])

# 1. 追加到 seed.html（在 <footer> 前）
sp = os.path.join(repo, "seed.html")
with open(sp, "rb") as f:
    raw = f.read()

footer_pos = raw.find(b"<footer>")
if footer_pos == -1:
    raise SystemExit("ERROR: <footer> not found in seed.html")

new_blocks = []
for i, (title, body) in enumerate(seeds, start=1):
    new_blocks.append(build_block(i, title, body))
insert = (CRLF.join(new_blocks) + CRLF).encode("utf-8")

new_raw = raw[:footer_pos] + insert + raw[footer_pos:]

# 校验 CRLF 完整性
bare_lf = new_raw.count(b"\n") - new_raw.count(b"\r\n")
with open(sp, "wb") as f:
    f.write(new_raw)

print("seed.html: old=%d new=%d insert=%d bare_LF=%d" % (len(raw), len(new_raw), len(insert), bare_lf))

# 2. 生成 seed-r75.html（从 seed-r74.html 模板现建）
