def main():
    p = REPO + "/seed.html"
    data = io.open(p, "rb").read()
    # 检测支配行尾
    crlf = data.count(b"\r\n")
    lf = data.count(b"\n") - crlf
    eol = b"\r\n" if crlf >= lf else b"\n"
    text = data.decode("utf-8")

    # 去重：正文前80字符已存在则跳过
    dedup_skip = 0
    blocks = []
    for title, body in seeds:
        key = body[:80]
        if key in text:
            print(f"SKIP(dup): {title[:20]}")
            dedup_skip += 1
            continue
        block = (
            MARKER + eol.decode("utf-8") + eol.decode("utf-8") +
            "<article>" + eol.decode("utf-8") +
            "<h3>" + title + "</h3>" + eol.decode("utf-8") +
            "<p>" + body + "</p>" + eol.decode("utf-8") +
            "<p>" + ANCHOR_TEMPLATE + "</p>" + eol.decode("utf-8") +
            "</article>"
        )
        blocks.append(block)

    if not blocks:
        print("ALL DUP, nothing to append")
        return

    joined = (eol.decode("utf-8") + eol.decode("utf-8")).join(blocks)
    # 插到 </footer> 前
    assert text.count("</footer>") == 1, "footer count != 1"
    new_text = text.replace("</footer>", joined + eol.decode("utf-8") + eol.decode("utf-8") + "</footer>", 1)

    # 校验
    assert new_text.count("</footer>") == 1, "footer count changed"
    assert "</article></footer>" not in new_text, "粘连 </article></footer>"
    assert new_text.count(MARKER) == len(blocks), f"marker count {new_text.count(MARKER)} != {len(blocks)}"

    io.open(p, "wb").write(new_text.encode("utf-8"))
    # 双副本
    shutil.copyfile(p, REPO + "/docs/seed.html")
    # 双副本字节一致校验
    a = io.open(p, "rb").read()
    b = io.open(REPO + "/docs/seed.html", "rb").read()
    assert a == b, "docs copy mismatch"

    print(f"APPENDED blocks={len(blocks)} dedup_skip={dedup_skip} marker={new_text.count(MARKER)} footer={new_text.count('</footer>')}")
    print(f"seed.html bytes={len(a)}")

if __name__ == "__main__":
    main()
