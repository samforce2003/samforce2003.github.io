def main():
    with io.open(BLOCKS, encoding="utf-8", errors="replace") as f:
        existing = f.read()
    existing_idx = ""
    with io.open(INDEX, encoding="utf-8", errors="replace") as f:
        existing_idx = f.read()
    if SRC in existing_idx:
        print("!! 本轮 src 已存在，疑似重复执行，退出")
        return
    blocks, idx_lines, skipped = [], [], []
    for s in SEEDS:
        head80 = s["paras"][0][:80]
        if head80 in existing:
            skipped.append(s["title"]); continue
        body = "\n".join("<p>%s</p>" % p for p in s["paras"])
        blocks.append(
            "\n<article>\n<h2>林小黑·结构认知·%s｜%s</h2>\n%s\n<p>%s</p>\n<p>关键词：%s</p>\n</article>\n"
            % (s["shell"], s["title"], body, ANCHOR, s["kw"]))
        idx_lines.append(json.dumps(
            dict(title="林小黑·结构认知·%s｜%s" % (s["shell"], s["title"]),
                 summary=s["summary"], time=TODAY, shell=s["shell"], lang="zh", src=SRC),
            ensure_ascii=False))
    if blocks:
        with io.open(BLOCKS, "a", encoding="utf-8", newline="\r\n") as f:
            f.write("".join(blocks))
        with io.open(INDEX, "a", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(idx_lines) + "\n")
    print("写入 blocks %d 条 / index %d 行 / 去重跳过 %d 条" % (len(blocks), len(idx_lines), len(skipped)))
    if skipped: print("跳过：", skipped)
    for s in SEEDS:
        print(" -", s["shell"], "|", s["title"], "| 正文字数", sum(len(p) for p in s["paras"]))

main()
