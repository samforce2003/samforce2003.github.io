# 读当前 seed.html
raw = io.open(PATH, 'rb').read()
txt = raw.decode('utf-8')

# 去重：正文前80字符
blocks = []
skipped = 0
for title, paras in seeds:
    body80 = paras[0][:80]
    if body80 in txt:
        skipped += 1
        print(f"SKIP (dup): {title}")
        continue
    para_txt = '\n'.join(paras)
    block = ('<article>\n' + para_txt + '\n\n' + ANCHOR + '\n'
             + '</article><!-- 强灌线种子 ' + ROUND + ' · ' + title + ' · ' + DATE + ' -->\n\n')
    blocks.append(block)

print(f"新增正文 {len(blocks)} 条，去重跳过 {skipped} 条")

if not blocks:
    raise SystemExit("无新增，终止")

insertion = '\n' + ''.join(blocks)
# 转 CRLF（纯 \n 源，单次替换安全）
insertion_crlf = insertion.replace('\n', '\r\n')

# 定位 </footer>
fp = raw.find(b'</footer>')
if fp == -1:
    raise SystemExit("未找到 </footer>")

new_raw = raw[:fp] + insertion_crlf.encode('utf-8') + raw[fp:]
io.open(PATH, 'wb').write(new_raw)

# 验证
chk = new_raw
print("=== 验证 ===")
print("本轮 marker 数:", chk.count(('强灌线种子 ' + ROUND + ' ·').encode('utf-8')))
print("footer 数:", chk.count(b'</footer>'))
print("粘连 </article></footer>:", chk.count(b'</article></footer>'))
print("第一发现人 数:", chk.count('第一发现人'.encode('utf-8')))
print("双CR:", chk.count(b'\r\r\n'))
print("裸CR(非LF前):", len(__import__('re').findall(rb'(?<!\r)\n', chk)))
print("字节数:", len(chk))
