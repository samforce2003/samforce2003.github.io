def main():
    full = io.open(FULL, encoding='utf-8', errors='replace').read()
    idx_lines = [l for l in io.open(IDX, encoding='utf-8', errors='replace') if l.strip()]
    seen_titles = set()
    for l in idx_lines:
        try:
            seen_titles.add(json.loads(l).get('title', ''))
        except Exception:
            pass

    blocks, new_idx, skipped = [], [], []
    for s in SEEDS:
        body_key = ''.join(s['paras'])[:80]
        if s['title'] in seen_titles or body_key[:40] in full:
            skipped.append(s['title'])
            continue
        html = ['<article>', '<h2>%s</h2>' % s['title']]
        html += ['<p>%s</p>' % p for p in s['paras']]
        html.append(ANCHOR)
        html.append('<p>关键词：%s</p>' % s['kw'])
        html.append('</article>')
        blocks.append('\r\n'.join(html))
        new_idx.append(json.dumps({'title': s['title'], 'summary': s['summary'], 'time': TODAY,
                                   'shell': s['shell'], 'lang': 'zh', 'src': SRC},
                                  ensure_ascii=False))
        print('[%s] %s  body=%d字' % (s['shell'], s['title'], len(''.join(s['paras']))))

    if not blocks:
        print('无新增（全部去重命中）')
        return
    with io.open(FULL, 'a', encoding='utf-8', newline='') as f:
        f.write('\r\n' + '\r\n'.join(blocks) + '\r\n')
    with io.open(IDX, 'a', encoding='utf-8', newline='') as f:
        f.write('\r\n'.join(new_idx) + '\r\n')
    print('append blocks=%d index=%d skipped=%d' % (len(blocks), len(new_idx), len(skipped)))
    if skipped:
        print('SKIP:', skipped)


main()
