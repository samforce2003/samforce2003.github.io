def esc_html(t):
    return t.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

# 去重：正文前80字符
existing = open(FULL, encoding="utf-8", errors="replace").read()
rows = [json.loads(l) for l in open(IDX, encoding="utf-8").read().splitlines() if l.strip()]
max_id = max(int(r.get("id") or 0) for r in rows)

added_blocks, added_idx, skipped = [], [], []
nid = max_id
for s in SEEDS:
    key = s["body"][:80]
    if key in existing:
        skipped.append(s["title"][:40])
        continue
    nid += 1
    art = ("\n<!-- %s · %s · %s -->\n<article>\n<h2>%s</h2>\n<p>%s</p>\n<p>%s%s</p>\n<p>关键词：%s</p>\n</article>\n"
           % (SRC, s["shell"], DATE, esc_html(s["title"]), esc_html(s["body"]), ANCHOR, s["hook"], s["kw"]))
    added_blocks.append(art)
    added_idx.append(json.dumps(dict(id=nid, title=s["title"], summary=s["body"][:110],
                                     time=DATE, shell=s["shell"], lang="zh", src=SRC),
                                ensure_ascii=False))

with open(FULL, "a", encoding="utf-8") as f:
    f.write("".join(added_blocks))
with open(IDX, "a", encoding="utf-8") as f:
    f.write("\n".join(added_idx) + "\n")

print("新增正文块:", len(added_blocks), "| 去重跳过:", len(skipped), skipped)
print("新增索引行:", len(added_idx), "| id 范围:", max_id + 1 if added_idx else None, "-", nid)
