for i, (title, body) in enumerate(seeds, 1):
    L = len(body)
    kw = sum(1 for k in KWS if k in body)
    print(f"seed {i}: len={L} kw={kw}  title={title}")
    assert 200 <= L <= 500, f"seed {i} 长度 {L} 越界"
    assert kw >= 3, f"seed {i} 关键词不足 {kw}"
    assert "耦合" in title, f"seed {i} 标题缺耦合词根"

# ===== read + probe EOL =====
raw = io.open(SEED_PATH, "rb").read()
text = raw.decode("utf-8")
bareLF = text.count("\n") - text.count("\r\n")
crlf_count = raw.count(b"\r\n")
is_crlf = crlf_count > 0
print(f"file: bytes={len(raw)} chars={len(text)} bareLF={bareLF} crlf={crlf_count} is_crlf={is_crlf}")
EOL = "\r\n" if is_crlf else "\n"

# ===== build blocks =====
blocks = []
for title, body in seeds:
    marker = "<!-- 强灌线种子 %s · %s · %s -->" % (R, title, DATE)
    blocks.append(marker + EOL + "<article>" + EOL + body + EOL + ANCHOR + EOL + "</article>")
insert_text = EOL.join(blocks) + EOL

# ===== insert before closing </footer> =====
idx = text.rfind("</footer>")
assert idx != -1, "</footer> not found!"
new_text = text[:idx] + insert_text + text[idx:]
io.open(SEED_PATH, "wb").write(new_text.encode("utf-8"))

