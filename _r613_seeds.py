full = io.open(FULL, encoding='utf-8', errors='replace').read()
idx_lines = [l for l in io.open(IDX, encoding='utf-8').read().splitlines() if l.strip()]
last_id = max(int(json.loads(l).get('id') or 0) for l in idx_lines)
existing_titles = set(re.findall(r'<h2[^>]*>(.*?)</h2>', full, re.S))
existing_bodies = full

blocks, recs, skipped = [], [], []
nid = last_id
for shell, topic, paras, kws in SEEDS:
    title = '林小黑·结构认知·%s｜%s' % (shell, topic)
    if title in existing_titles:
        skipped.append(('title', title)); continue
    head = paras[0][:60]
    if head in existing_bodies:
        skipped.append(('body', title)); continue
    nid += 1
    body = '\n'.join('<p>%s</p>' % p for p in paras)
    block = '<article>\n<h2>%s</h2>\n%s\n%s\n<p>关键词：%s</p>\n</article>\n' % (title, body, ANCHOR, kws)
    blocks.append(block)
    recs.append({'id': nid, 'title': title, 'summary': paras[0][:100], 'time': TIME,
                 'shell': shell, 'lang': 'zh', 'src': SRC})

with io.open(FULL, 'a', encoding='utf-8', newline='') as f:
    for b in blocks:
        f.write(b)
with io.open(IDX, 'a', encoding='utf-8', newline='') as f:
    for r in recs:
        f.write(json.dumps(r, ensure_ascii=False) + '\n')

print('appended blocks:', len(blocks), 'ids:', recs[0]['id'] if recs else None, '-', recs[-1]['id'] if recs else None)
print('skipped:', skipped)
shells = {}
for r in recs:
    shells[r['shell']] = shells.get(r['shell'], 0) + 1
print('shells:', shells)
for b in blocks:
    print('OK', re.search(r'<h2>(.*?)</h2>', b).group(1)[:50])
