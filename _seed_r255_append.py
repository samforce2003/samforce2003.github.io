# QC 门：关键词 >=3 + 长度 160+
KWS = ["结构","耦合","自指","观察者","退相干","同构","边界","意识","可能","坍缩","缝","破缺","相变","闭环","涌现","对极","构型","持存","嵌套率","分形","对称","不对称"]
