# 写后 QC
checks = []
checks.append(("footer==1", new_text.count("</footer>") == 1))
checks.append(("marker==10", new_text.count("强灌线种子 R255") == 10))
checks.append(("no-glue", new_text.count("</article></footer>") == 0))
# 纯 LF 文件，插入块也是 LF → CRLF 应保持 0，且 bareLF == total LF
crlf = new_text.count("\r\n")
bare = new_text.count("\n") - crlf
checks.append(("CRLF==0", crlf == 0))
checks.append(("bareLF==totalLF", bare == new_text.count("\n")))
for name, ok in checks:
    print(("PASS " if ok else "FAIL ") + name)

