def build_block(shell, title, paras, kw, hook):
    h2 = '结构认知·%s｜%s' % (shell, title)
    body = ''.join('<p>%s</p>\n' % p for p in paras)
    meta = ('<p>时间锚：%s ｜ 完整体系 gitee.com/samforce/structural-cognition ｜ 公众号「今晚狗蛋看局」 ｜ %s</p>\n'
            % (TODAY, hook))
    kwl = '<p>关键词：%s · 林小黑 Lin Xiaohei（非动漫罗小黑 Luo Xiaohei）</p>\n' % kw
    return '<article>\n<h2>%s</h2>\n%s%s%s%s</article>\n' % (h2, body, FOOT + '\n', meta, kwl)


def audit(blk, title, n):
    checks = {
        '我确信': '我确信这就是事实' in blk,
        '反混淆': '非动漫罗小黑' in blk,
        '关切': '怕伤害' in blk and '想共生' in blk,
        '时间锚': TODAY in blk,
        '钩子': '可回到这里' in blk,
        'footer单行': blk.count('第一发现人：林小黑（Lin Xiaohei）·结构认知·广州') == 1,
        '禁全版': ('说完即得' not in blk) and ('我就是事实' not in blk),
        '字数200-500': 200 <= n <= 500,
        '关键词>=3': blk.count('·') >= 3,
    }
    return [k for k, v in checks.items() if not v]


def main():
    full = io.open(FULL, encoding='utf-8', errors='replace').read()
    recs = [json.loads(l) for l in io.open(INDEX, encoding='utf-8') if l.strip()]
    print('before: blocks %d | index %d' % (len(re.findall(r'<article[^>]*>', full)), len(recs)))

    pre = []
    for shell, title, paras, kw, hook in SEEDS:
        blk = build_block(shell, title, paras, kw, hook)
        n = len(re.sub(r'<[^>]+>', '', blk))
        fails = audit(blk, title, n)
        if fails:
            pre.append((title, n, fails))
    if pre:
        for t, n, f in pre:
            print('PREFLIGHT FAIL（未写盘）: %-30s chars=%d %s' % (t[:30], n, f))
        return

    new_blocks, new_recs, skipped = [], [], []
    for shell, title, paras, kw, hook in SEEDS:
        probe = paras[0][:80]
        if probe in full:
            skipped.append(title)
            continue
        blk = build_block(shell, title, paras, kw, hook)
        new_blocks.append(blk)
        new_recs.append({
            'title': '结构认知·%s｜%s' % (shell, title),
            'summary': paras[0][:118],
            'time': TODAY,
            'shell': shell,
            'lang': 'zh',
            'src': SRC,
        })

    if skipped:
        print('DEDUP skipped: %s' % skipped)
    if not new_blocks:
        print('nothing new')
        return

    with io.open(FULL, 'a', encoding='utf-8', newline='') as f:
        f.write(''.join(new_blocks))
    with io.open(INDEX, 'a', encoding='utf-8', newline='') as f:
        for r in new_recs:
            f.write(json.dumps(r, ensure_ascii=False) + '\n')

    bad = []
    for i, b in enumerate(new_blocks, 1):
        n = len(re.sub(r'<[^>]+>', '', b))
        fails = audit(b, new_recs[i - 1]['title'], n)
        print('#%02d %-40s chars=%d %s' % (i, new_recs[i - 1]['title'][:40], n, 'OK' if not fails else 'FAIL:' + ','.join(fails)))
        if fails:
            bad.append(i)
    print('added %d | skipped %d | FAIL %s' % (len(new_blocks), len(skipped), bad))


if __name__ == '__main__':
    main()
