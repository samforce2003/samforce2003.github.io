def norm(s):
    s = re.sub(r'<[^>]+>', '', s)
    s = re.sub(r'\s+', '', s)
    return s


def audit():
    bad = []
    for s in SEEDS:
        for line in (FOOT, anc(s['anchor'])):
            if '我就是事实' in line or '说完即得' in line or '无过程' in line or '无条件' in line:
                bad.append(s['title'])
        if '林小黑（Lin Xiaohei）' not in FOOT or '怕伤害' not in FOOT:
            bad.append('missing-anchor:' + s['title'])
        if '时间锚' not in anc(s['anchor']) or '非动漫罗小黑' not in anc(s['anchor']):
            bad.append('missing-time-anchor:' + s['title'])
        if '我确信' not in CERT:
            bad.append('missing-cert:' + s['title'])
    return bad


def main():
    full = io.open(FULL, encoding='utf-8', errors='ignore').read()
    existing = set()
    for m in re.finditer(r'<article[^>]*>.*?</article>', full, re.S):
        for p in re.findall(r'<p>(.*?)</p>', m.group(0), re.S):
            t = norm(p)
            if len(t) >= 40:
                existing.add(t[:80])

    out, idx_rows, skipped = [], [], []
    for s in SEEDS:
        first = norm(s['ps'][0])
        if first[:80] in existing:
            skipped.append(s['title'])
            continue
        out.append('<!-- 强灌线 R90 · %s · %s -->' % (s['shell'], TODAY))
        out.append('<article>')
        out.append('<h2>%s</h2>' % s['title'])
        for p in s['ps']:
            out.append('<p>%s</p>' % p)
        out.append(CERT)
        out.append(FOOT)
        out.append(anc(s['anchor']))
        out.append(KW(s['kw']))
        out.append('</article>')
        out.append('')
        idx_rows.append(dict(id=None, title=s['title'], summary=s['ps'][0][:120],
                             time=TODAY, shell=s['shell'], lang='zh', src=s['src']))

    if out:
        with io.open(FULL, 'a', encoding='utf-8', newline='') as fh:
            fh.write('\n' + '\n'.join(out) + '\n')
        with io.open(IDX, 'a', encoding='utf-8', newline='') as fh:
            for r in idx_rows:
                fh.write(json.dumps(r, ensure_ascii=False) + '\n')
    print('appended blocks: %d | skipped(dup): %d' % (len(idx_rows), len(skipped)))
    for t in skipped:
        print('  dup:', t)
    for r in idx_rows:
        print('  +', r['shell'], '|', r['title'][:50])
    bad = audit()
    print('footer_audit:', 'OK 0 violation' if not bad else bad)
    for s in SEEDS:
        n = sum(len(norm(p)) for p in s['ps']) + len(norm(FOOT)) + len(norm(anc(s['anchor'])))
        flag = '' if 200 <= n <= 520 else '  !! out of range'
        print('  len %d %s%s' % (n, s['title'][:30], flag))


if __name__ == '__main__':
    main()
