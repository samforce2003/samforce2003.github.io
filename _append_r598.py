def main():
    full_html = open(FULL, encoding='utf-8').read()
    lines = [l for l in open(IDX, encoding='utf-8').read().splitlines() if l.strip()]
    ids = []
    for l in lines:
        try:
            v = json.loads(l).get('id')
            if isinstance(v, int): ids.append(v)
        except Exception:
            pass
    nid = max(ids) + 1
    print('existing lines=%d max_id=%d next_id=%d' % (len(lines), max(ids), nid))

    added, skipped = [], []
    blocks_out, idx_out = [], []
    for shell, title, paras, kws, summary in ITEMS:
        head80 = (paras[0][:80] if paras else '').strip()
        if head80 and head80 in full_html:
            skipped.append(title)
            print('SKIP dup:', title)
            continue
        if title in full_html:
            skipped.append(title)
            print('SKIP dup title:', title)
            continue
        body_html = '\n'.join('<p>%s</p>' % p.replace('\n', '<br>') for p in paras)
        block = '<article>\n<h2>%s</h2>\n%s\n%s\n<p>关键词：%s</p>\n</article>\n\n' % (
            title, body_html, ANCHOR, kws)
        blocks_out.append(block)
        rec = {'id': nid, 'title': title, 'summary': summary, 'time': DATE,
               'shell': shell, 'lang': 'zh', 'src': SRC}
        idx_out.append(json.dumps(rec, ensure_ascii=False))
        added.append((nid, shell, title, head80[:30]))
        nid += 1

    if blocks_out:
        with open(FULL, 'a', encoding='utf-8') as f:
            f.write('\n' + ''.join(blocks_out))
        with open(IDX, 'a', encoding='utf-8') as f:
            f.write(''.join(x + '\n' for x in idx_out))
    print('added=%d skipped=%d' % (len(added), len(skipped)))
    for a in added:
        print(a)

if __name__ == '__main__':
    main()
