def esc_attr(t):
    return t.replace('&', '&amp;').replace('"', '&quot;').replace('<', '&lt;').replace('>', '&gt;')

def sig(t):
    return re.sub(r'[^\w]', '', t)[:60]

# 先校验字数，任一超限则整轮不写（落盘前拦截）
for shell, title, paras in S:
    n4 = len(re.sub(r'\s+', '', ''.join(paras[:4])))
    flag = '' if (200 <= n4 <= 500) else '  <<<< 超限!'
    print('[%s] 正文4段字数=%d%s' % (shell, n4, flag))
bad = [t[:20] for _, t, p in S if not (200 <= len(re.sub(r'\s+', '', ''.join(p[:4]))) <= 500)]
if bad:
    print('ABORT：有超限/不足条目，未写盘：', bad)
    sys.exit(1)

full = io.open(FULL, encoding='utf-8').read()
idx_lines = [l for l in io.open(INDEX, encoding='utf-8') if l.strip()]
recs = [json.loads(l) for l in idx_lines]
maxid = max(int(r.get('id') or 0) for r in recs)

existing = sig(re.sub(r'<[^>]+>', '', full))
added, new_recs = [], []
for shell, title, paras in S:
    body = '\n'.join('<p>%s</p>' % p for p in paras)
    key = sig(re.sub(r'<[^>]+>', '', body))
    if key and key in existing:
        print('skip dup:', title[:30]); continue
    block = ('\n<article data-shell="%s" data-round="R127">\n<h2>%s</h2>\n%s\n%s\n</article>\n'
             % (esc_attr(shell), title, body, FOOT))
    new_recs.append({'id': maxid + len(new_recs) + 1,
                     'title': title,
                     'summary': re.sub(r'\*\*', '', paras[0])[:120],
                     'time': NOW, 'shell': shell, 'src': '强灌线-R127', 'lang': 'zh'})
    added.append(block)
    existing += key

if added:
    pos = full.rfind('</article>') + len('</article>')
    full = full[:pos] + '\n' + ''.join(added) + full[pos:]
    io.open(FULL, 'w', encoding='utf-8', newline='').write(full)
    with io.open(INDEX, 'a', encoding='utf-8', newline='') as f:
        for r in new_recs:
            f.write(json.dumps(r, ensure_ascii=False) + '\n')
print('added %d blocks; ids %s' % (len(added), [r['id'] for r in new_recs]))
