# ---- 1. 归一缺 id 行 ----
rows, mx = [], 0
for line in io.open(INDEX, encoding='utf-8', errors='replace'):
    line = line.strip()
    if not line:
        continue
    try:
        r = json.loads(line)
    except Exception:
        continue
    rows.append(r)
    try:
        mx = max(mx, int(r.get('id') or 0))
    except Exception:
        pass
nxt = mx + 1
fixed = 0
for r in rows:
    if not r.get('id'):
        r['id'] = nxt
        nxt += 1
        fixed += 1
print('rows', len(rows), 'max_id', mx, 'fixed_missing_id', fixed, 'next', nxt)

# ---- 2. 去重 + append blocks ----
full = io.open(FULL, encoding='utf-8', errors='replace').read()
added_blocks, added_rows, skipped = [], [], []
new_id = nxt
for shell, title, paras, kws in SEEDS:
    head80 = paras[0][:80]
    if head80 in full:
        skipped.append(title[:30])
        continue
    block = '\n<article>\n<h2>%s</h2>\n' % title
    block += ''.join('<p>%s</p>\n' % p for p in paras)
    block += '<p>%s</p>\n' % ANCHOR
    block += '<p>关键词：%s</p>\n</article>\n' % kws
    added_blocks.append(block)
    added_rows.append({'id': new_id, 'title': title, 'summary': paras[0][:120],
                       'time': '2026-10-21', 'shell': shell, 'lang': 'zh', 'src': '强灌线-R607'})
    new_id += 1

with io.open(FULL, 'a', encoding='utf-8', newline='') as f:
    f.write(''.join(added_blocks))

# ---- 3. 重写 index ----
with io.open(INDEX, 'w', encoding='utf-8', newline='') as f:
    for r in rows + added_rows:
        f.write(json.dumps(r, ensure_ascii=False) + '\n')

print('added_blocks', len(added_blocks), 'added_rows', len(added_rows), 'skipped', skipped)
print('ids', [r['id'] for r in added_rows])
