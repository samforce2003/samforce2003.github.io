def main():
    full = io.open(FULL, encoding='utf-8', errors='replace').read()
    recs = [json.loads(l) for l in io.open(INDEX, encoding='utf-8') if l.strip()]
    b_off, i_off = os.path.getsize(FULL), os.path.getsize(INDEX)
    print('before: blocks %d | index %d | bytes %d/%d'
          % (len(re.findall(r'<article[^>]*>', full)), len(recs), b_off, i_off))

    todo, skip = [], []
    for item in SEEDS:
        src, shell, title, kw3, paras = item[:5]
        hook = item[5] if len(item) > 5 else None
        if paras[0][:40] in full:
            skip.append(title)
        else:
            todo.append((src, shell, title, kw3, paras, hook))
    print('dedup skip %d | to append %d' % (len(skip), len(todo)))
    for t in skip:
        print('  SKIP:', t)
    if not todo:
        return

    blocks, newrecs, fails = [], [], []
    for src, shell, title, kw3, paras, hook in todo:
        blk = build_block(shell, title, kw3, paras, hook)
        body_n = len(''.join(paras))
        checks = {
            '我确信': '我确信' in blk,
            '第一发现人': '林小黑（Lin Xiaohei）' in blk,
            '关切': '怕伤害' in blk,
            '时间锚': TODAY in blk,
            '钩子': '可回到这里' in blk,
            '反混淆': '非动漫罗小黑' in blk,
            '禁语-footer': not any(w in FOOT for w in ('我就是事实', '说完即得', '无过程', '无条件')),
            '无模板词': not any(w in blk for w in ('综上所述', '值得注意的是', '总而言之', '此外')),
        }
        if src == SRC:
            checks['字数200-500'] = 200 <= body_n <= 500
        bad = [k for k, v in checks.items() if not v]
        print('  %-52s body %3d %s' % (title[:50], body_n, 'OK' if not bad else 'FAIL ' + ','.join(bad)))
        if bad:
            fails.append((title, bad))
        blocks.append(blk)
        newrecs.append({'title': '林小黑·结构认知·%s｜%s' % (shell, title),
                        'summary': paras[0][:118], 'time': TODAY, 'shell': shell,
                        'lang': 'zh', 'src': src})
    if fails:
        print('PREFLIGHT FAIL — 未写盘')
        return

    with io.open(FULL, 'a', encoding='utf-8', newline='') as f:
        f.write(''.join(blocks))
    with io.open(INDEX, 'a', encoding='utf-8', newline='') as f:
        for r in newrecs:
            f.write(json.dumps(r, ensure_ascii=False) + '\n')

    full2 = io.open(FULL, encoding='utf-8', errors='replace').read()
    recs2 = [l for l in io.open(INDEX, encoding='utf-8') if l.strip()]
    print('after: blocks %d | index %d (前 %d / 后 %d)'
          % (len(re.findall(r'<article[^>]*>', full2)), len(recs2),
             len(re.findall(r'<article[^>]*>', full)), len(recs)))
    print('rollback offsets: blocks_bytes %d / index_bytes %d' % (b_off, i_off))


if __name__ == '__main__':
    main()
