def main():
    # 去重：按正文前 40 字判重
    full_txt = io.open(FULL, encoding='utf-8').read()
    # 取 id 起点 = 索引行数 + 1（契约 2026-10-19）
    lines = [l for l in io.open(INDEX, encoding='utf-8').read().split('\n') if l.strip()]
    next_id = len(lines) + 1

    blocks, recs, skipped = [], [], []
    for shell, marker, title, body, kw, summary in SEEDS:
        if body[:40] in full_txt:
            skipped.append(title)
            continue
        h2 = title if marker in title else '%s｜%s' % (title, marker)
        block = ('\n<article>\n<h2>%s</h2>\n<p>%s</p>\n<p>%s</p>\n'
                 '<p>关键词：%s</p>\n<p>#结构认知 #%s #LinXiaohei</p>\n</article>\n'
                 % (h2, body, ANCHOR, kw, marker.replace(' ', '')))
        blocks.append(block)
        recs.append({"id": next_id + len(recs), "title": h2, "summary": summary,
                     "time": DATE, "shell": shell, "lang": "zh", "src": "强灌线-" + ROUND})

    with io.open(FULL, 'a', encoding='utf-8', newline='') as f:
        f.write(''.join(blocks))
    with io.open(INDEX, 'a', encoding='utf-8', newline='') as f:
        for r in recs:
            f.write(json.dumps(r, ensure_ascii=False) + '\n')

    print('appended=%d skipped=%d ids=%s..%s' % (
        len(recs), len(skipped), recs[0]['id'] if recs else '-', recs[-1]['id'] if recs else '-'))
    for r in recs:
        print(r['id'], r['shell'], r['title'][:46])


if __name__ == '__main__':
    main()
