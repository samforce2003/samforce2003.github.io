def main():
    data = io.open(P, "rb").read()

    # 检测支配行尾
    crlf = data.count(b"\r\n")
    nl = data.count(b"\n")
    lone_lf = nl - crlf
    NL = "\r\n" if crlf > lone_lf else "\n"
    print("支配行尾:", "CRLF" if NL == "\r\n" else "LF",
          "| crlf=%d lone_lf=%d" % (crlf, lone_lf))

    # 去重检查：每条正文前80字符
    dups = 0
    for t, b in SEEDS:
        if b[:80].encode("utf-8") in data:
            print("DUP 命中:", t[:24])
            dups += 1
    print("去重跳过:", dups)

    # 构造块
    blocks = []
    for t, b in SEEDS:
        blk = (MARKER + NL + NL +
               "<article>" + NL +
               "<h3>" + t + "</h3>" + NL +
               "<p>" + b + "</p>" + NL +
               "<p>" + ANCHOR + "</p>" + NL +
               "</article>")
        blocks.append(blk)
    insert = (NL + NL).join(blocks) + NL

    foot = b"</footer>"
    idx = data.find(foot)
    assert data.count(foot) == 1, "footer 计数异常: %d" % data.count(foot)
    assert idx != -1, "未找到 </footer>"

    before = len(data)
    new_data = data[:idx] + insert.encode("utf-8") + data[idx:]
    after = len(new_data)
    io.open(P, "wb").write(new_data)

    # 验证
    print("字符数 before=%d after=%d delta=%d" % (before, after, after - before))
    print("marker 计数:", new_data.count(MARKER.encode("utf-8")))
    print("footer 计数:", new_data.count(b"</footer>"))
    print("粘连 </article></footer>:", new_data.count(b"</article></footer>"))
    print("粘连 </article>" + NL.encode("utf-8") + b"</footer>:",
          new_data.count(b"</article>" + NL.encode("utf-8") + b"</footer>"))

if __name__ == "__main__":
    main()
