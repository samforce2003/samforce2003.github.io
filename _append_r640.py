def main():
    full = io.open(FULL, encoding='utf-8').read()
    tail = full[-400000:]
    added, skipped = [], []
    blocks_out, lines_out = [], []
    for s in SEEDS:
        head = s['paras'][0][:80]
        if head and head in tail:
            skipped.append(s['title']); continue
        body = '\n<h2>%s</h2>\n' % s['title'] + '\n'.join('<p>%s</p>' % p for p in s['paras']) + \
               '\n<p>%s</p>\n<p>关键词：%s</p>\n' % (ANCHOR, s['kw'])
        block = '<article>\n%s</article>\n' % body
        blocks_out.append(block)
        rec = dict(id=None, title=s['title'], summary=s['summ'], time=TIME,
                   shell=s['shell'], lang='zh', src=SRC)
        lines_out.append(json.dumps(rec, ensure_ascii=False))
        n = len(re.sub(r'<[^>]+>', '', body))
        added.append((s['shell'], s['title'], s['paras'][0][:30], n))

    if blocks_out:
        with io.open(FULL, 'a', encoding='utf-8', newline='') as f:
            f.write('\n' + '\n'.join(blocks_out))
        with io.open(IDX, 'a', encoding='utf-8', newline='') as f:
            for l in lines_out:
                f.write(l + '\n')

    print('added=%d skipped=%d' % (len(added), len(skipped)))
    for a in added:
        print('%s | %s | %s | %d字' % a)
    for t in skipped:
        print('SKIP', t)


if __name__ == '__main__':
    main()
