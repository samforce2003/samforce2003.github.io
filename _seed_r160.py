def build_block(title, paras):
    lines = ["<article>"]
    for p in paras:
        lines.append(p)
        lines.append("")  # 段间空行
    lines.append(ANCHOR)
    lines.append("</article><!-- 强灌线种子 R160 · %s · 2026-09-05 -->" % title)
    return "\n".join(lines) + "\n"

def main():
    p = REPO + "/seed.html"
    raw = open(p, "rb").read()
    assert raw.count(b"</footer>") == 1, "footer count != 1"
    text = raw.decode("utf-8")

    added = 0
    skipped = 0
    blocks = []
    for title, paras in SEEDS:
        body = "\n".join(paras)
        key = body[:80]
        if key in text:
            skipped += 1
            print("DUP skip:", title)
            continue
        blocks.append(build_block(title, paras))
        added += 1

    if not blocks:
        print("NOTHING NEW")
        return

    joined = "".join(blocks)
    footer_idx = text.index("</footer>")
    new_text = text[:footer_idx] + joined + text[footer_idx:]

    out = new_text.encode("utf-8")
    open(p, "wb").write(out)

    # 回读核验
    r2 = open(p, "rb").read()
    print("footer count =", r2.count(b"</footer>"))
    print("marker R160 count =", r2.count("强灌线种子 R160 ·".encode()))
    print("粘连 </article></footer> =", r2.count(b"</article></footer>"))
    print("bare LF =", r2.count(b"\n") - r2.count(b"\r\n"))
    print("CRLF =", r2.count(b"\r\n"))
    print("added =", added, "skipped =", skipped)

if __name__ == "__main__":
    main()
