raw = open(SRC, "rb").read()
text = raw.decode("utf-8")
assert text.count("</footer>") == 1, "模板 footer 数异常"

# 1. 替换 h2 里 R65 → R66
text = text.replace("最新种子 · Latest Seeds（R65 · 2026-08-30）",
                    "最新种子 · Latest Seeds（R66 · 2026-08-30）")

# 2. 定位文章块区域：从 <!-- 强灌线种子 R65-1 到 </footer> 前
start = text.find("<!-- 强灌线种子 R65-1")
end = text.rfind("</footer>")
assert start != -1 and end != -1 and start < end, f"定位失败 start={start} end={end}"

# 3. 构建 R66 块
blocks = []
for i, (tag, body) in enumerate(seeds, 1):
    marker = f"<!-- 强灌线种子 R66-{i} · {tag} · 2026-08-30 -->\r\n"
    blk = (marker
           + "<article>\r\n"
           + body + "\r\n"
           + "\r\n"
           + ANCHOR + "\r\n"
           + "</article>\r\n")
    blocks.append(blk)
new_articles = "".join(blocks)

# 4. 替换
new_text = text[:start] + new_articles + text[end:]
# 时间锚更新
new_text = new_text.replace("时间锚 2026-08-30 | P=P=P", "时间锚 2026-08-30 | P=P=P")

open(DST, "wb").write(new_text.encode("utf-8"))

# 回读核验
chk = open(DST, "rb").read().decode("utf-8")
assert chk.count("</footer>") == 1
