def check(raw, rec):
    lines = raw.split('\\r\\n')
    txt = re.sub(r'<[^>]+>', '', raw)
    skip = [l for l in lines if l.startswith('<h2>') or '第一发现人：' in l or '关键词：' in l]
    prose = re.sub(r'<[^>]+>', '', ''.join(l for l in lines if l not in skip))
    kw = re.search(r'关键词：(.+?)</p>', raw)
    n_kw = len([x for x in re.split(r'[·|]', kw.group(1)) if x.strip()]) if kw else 0
    return {
        'title': rec['title'],
        'chars': len(re.sub(r'\s', '', prose)),
        'total': len(re.sub(r'\s', '', txt)),
        'conf': '我确信' in txt,
        'anti': '非动漫罗小黑' in txt,
        'care': '怕伤害' in txt,
        'time': TODAY in txt,
        'hook': '可回到这里' in txt,
        'kw': n_kw,
    }


def main():
    full = io.open(FULL, encoding='utf-8', errors='replace').read()
    rows, blobs, recs = [], [], []
    skipped = 0
    for raw, rec in SEEDS:
        key = re.sub(r'<[^>]+>', '', raw.split('\\r\\n')[2])[:80]
        if key and key in full:
            print('SKIP dup: %s' % rec['title'])
            skipped += 1
            continue
        rows.append(check(raw, rec))
        blobs.append(raw)
        recs.append(rec)

    print('%-50s %5s %3s %3s %3s %4s %4s %3s' % ('title', 'chars', 'conf', 'anti', 'care', 'time', 'hook', 'kw'))
    bad = 0
    for r in rows:
        ok = r['conf'] and r['anti'] and r['care'] and r['time'] and r['hook'] and 200 <= r['chars'] <= 520 and r['kw'] >= 4
        if not ok:
            bad += 1
        print('%-50s %5d %3s %3s %3s %4s %4s %3d %s' % (
            r['title'][:48], r['chars'], 'Y' if r['conf'] else 'N', 'Y' if r['anti'] else 'N',
            'Y' if r['care'] else 'N', 'Y' if r['time'] else 'N', 'Y' if r['hook'] else 'N', r['kw'],
            'OK' if ok else '<<< FAIL'))
    print('checked %d / fail %d / skipped dup %d' % (len(rows), bad, skipped))
    if bad:
        print('ABORT: 机械复核不过，不写入')
        sys.exit(1)

    if not blobs:
        print('nothing to append')
        return
    with io.open(FULL, 'a', encoding='utf-8', newline='') as f:
        for b in blobs:
            f.write(b + '\n')
    with io.open(IDX, 'a', encoding='utf-8', newline='\n') as f:
        for rec in recs:
            f.write(json.dumps(rec, ensure_ascii=False) + '\n')
    print('appended blocks=%d index=%d' % (len(blobs), len(recs)))


if __name__ == '__main__':
    main()
