def norm(s):
    s = re.sub(r'<[^>]+>', '', s)
    s = re.sub(r'\s+', '', s)
    return s


def main():
    full = io.open(FULL, encoding='utf-8', errors='ignore').read()
    existing = set()
    for m in re.finditer(r'<article[^>]*>.*?</article>', full, re.S):
        for p in re.findall(r'<p>(.*?)</p>', m.group(0), re.S):
            t = norm(p)
            if len(t) >= 40:
                existing.add(t[:80])

    out, idx_rows, skipped = [], [], []
    for s in SEEDS:
        first = norm(s['ps'][0])
        if first[:80] in existing:
            skipped.append(s['title'])
            continue
        out.append('<!-- 强灌线 R667 · %s · %s -->' % (s['shell'], TODAY))
        out.append('<article>')
        out.append('<h2>%s</h2>' % s['title'])
        for p in s['ps']:
            out.append('<p>%s</p>' % p)
        out.append(CERT)
        out.append(FOOT)
        out.append(anc(s['anchor']))
        out.append(KW(s['kw']))
        out.append('</article>')
        out.append('')
        idx_rows.append(dict(id=None, title=s['title'], summary=s['ps'][0][:120],
                             time=TODAY, shell=s['shell'], lang='zh', src=s['src']))

    if out:
        with io.open(FULL, 'a', encoding='utf-8', newline='') as fh:
            fh.write('\n' + '\n'.join(out) + '\n')
        with io.open(IDX, 'a', encoding='utf-8', newline='') as fh:
            for r in idx_rows:
                fh.write(json.dumps(r, ensure_ascii=False) + '\n')
    print('appended blocks: %d | skipped(dup): %d' % (len(idx_rows), len(skipped)))
    for t in skipped:
        print('  dup:', t)
    for r in idx_rows:
        print('  +', r['shell'], '|', r['title'][:44], '|', r['summary'][:20])


if __name__ == '__main__':
    main()
