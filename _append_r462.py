def build_article(title, body):
    return ('\n强灌线种子 ' + ROUND + '\n\n'
            '<article>\n'
            '<h3>' + title + '</h3>\n'
            '<p>' + body + '</p>\n'
            '<p>' + ANCHOR + '</p>\n'
            '</article>\n')

with open(SEED_FILE, 'r', encoding='utf-8') as f:
    html = f.read()

if ('强灌线种子 ' + ROUND) in html:
    print("ERROR: marker 强灌线种子 " + ROUND + " already exists")
    sys.exit(1)

# 校验字数（全部须 200-500）
all_ok = True
for t, b in seeds:
    n = len(b)
    flag = "OK" if 200 <= n <= 500 else "LEN_BAD"
    if flag != "OK":
        all_ok = False
    print(f"[{flag}] len={n} {t[:24]}")

# 标题唯一性（不重复已存在标题）
title_dup = 0
for t, b in seeds:
    if ('<h3>' + t + '</h3>') in html:
        title_dup += 1
        print("TITLE_DUP:", t)

# 去重（正文前80字符）
dedup_skip = 0
for t, b in seeds:
    if b[:80] in html:
        dedup_skip += 1
        print("DEDUP_SKIP:", t)

if not all_ok:
    print("ABORT: some seeds < 200 chars, fix and rerun")
    sys.exit(2)

if title_dup:
    print("ABORT: title collision with existing content")
    sys.exit(3)

block = "".join(build_article(t, b) for t, b in seeds)

assert html.count('</footer>') == 1, "footer count != 1"
html = html.replace('</footer>', block + '</footer>', 1)

with open(SEED_FILE, 'w', encoding='utf-8', newline='') as f:
    f.write(html)

