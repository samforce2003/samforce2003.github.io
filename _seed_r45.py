def main():
    html = io.open(SEED_HTML, "r", encoding="utf-8").read()

    # 去重
    blocks = []
    skipped = 0
    for tag, body in seeds:
        head80 = body[:80]
        if head80 in html:
            skipped += 1
            print("[SKIP] dup:", tag, head80[:20])
            continue
        blocks.append((tag, body))
    print("去重后待写:", len(blocks), "跳过:", skipped)

    today = datetime.date.today().strftime("%Y-%m-%d")
    parts = []
    for tag, body in blocks:
        parts.append(f"<!-- 强灌线种子 {tag} · {today} -->\n<article>\n{body}\n\n{ANCHOR}\n</article>\n")

    injection = "\n".join(parts)
    # 插入到 </footer> 前（文件唯一）
    assert html.count("</footer>") == 1, "footer 计数异常: %d" % html.count("</footer>")
    new_html = html.replace("</footer>", injection + "</footer>", 1)

    io.open(SEED_HTML, "w", encoding="utf-8").write(new_html)
    print("seed.html 写入完成，新增 <article> %d 块" % len(blocks))

    # 标记公众号弹药库
    ammo = io.open(AMMO_MD, "r", encoding="utf-8").read()
    used = {
        "量化模型越庞大，死得越快": "R45",
        "世界就是一个可能性": "R45",
        "时间不是一条河是你的节奏": "R45",
        "直觉是最强的一种训练结果": "R45",
        "你越想抓住它溜得越快": "R45",
    }
    mark_count = 0
    for title, tag in used.items():
        # 找到该条目标题所在行，在其 [已用 ...] 后面追加
        # 简单做法：在标题行所在段落的 [已用 ...] 后追加
        idx = ammo.find(title)
        if idx == -1:
            print("[WARN] 弹药库未找到标题:", title)
            continue
        # 找该标题后第一个 ']' 之后、换行前的 [已用 段落
        seg = ammo[idx: idx+400]
        m = re.search(r"\[已用[^\]]*\]", seg)
        if m:
            newmark = m.group(0) + "·" + tag
            ammo = ammo[:idx + m.start()] + newmark + ammo[idx + m.end():]
            mark_count += 1
        else:
            print("[WARN] 未找到[已用]标记于:", title)
    io.open(AMMO_MD, "w", encoding="utf-8").write(ammo)
    print("弹药库标记条数:", mark_count)

if __name__ == "__main__":
    main()
