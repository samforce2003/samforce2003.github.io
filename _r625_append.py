new_blocks, new_idx, skipped = [], [], []
for d in S:
    head = d["paras"][0][:80]
    if head in existing:
        skipped.append(d["title"])
        continue
    body = "\n".join("<p>%s</p>" % p for p in d["paras"])
    block = ("<article>\r\n<h2>%s</h2>\r\n%s\r\n<p>我确信：%s</p>\r\n<p>%s</p>\r\n<p>关键词：%s</p>\r\n</article>\r\n\r\n"
             % (d["title"], body, d["believe"], ANCHOR.format(date=DATE, hook=d["hook"]), d["kw"]))
    new_blocks.append(block)
    new_idx.append(json.dumps({
        "id": None, "title": d["title"], "summary": d["summary"], "time": DATE,
        "shell": d["shell"], "lang": "zh", "src": SRC
    }, ensure_ascii=False))

with io.open(FULL, "a", encoding="utf-8", newline="") as f:
    f.write("".join(new_blocks))
with io.open(IDX, "a", encoding="utf-8", newline="") as f:
    for l in new_idx:
        f.write(l + "\r\n")

print("appended blocks:", len(new_blocks), "index lines:", len(new_idx), "skipped:", len(skipped))
