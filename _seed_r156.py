# ---- 1. 构建 10 个 block（CRLF，匹配 R155 既有格式：</article> 后紧接下一个 marker）----
blocks = []
for title, body in SEEDS:
    # 校验：正文无 ASCII 双引号/单引号
    assert '"' not in body and "'" not in body, f"ASCII quote in: {title}"
    blk = (
        f"<!-- 强灌线种子 {ROUND} · {title} · {DATE} -->\r\n"
        f"<article>\r\n"
        f"{body}\r\n\r\n"
        f"{ANCHOR}\r\n"
        f"</article>"
    ).encode("utf-8")
    blocks.append(blk)

insert = b"".join(blocks) + b"\r\n"  # 尾 \r\n 分隔最后一个 </article> 与 </footer>

# ---- 2. seed.html 追加（rb/wb，rfind </footer>）----
p = f"{SEED_DIR}/seed.html"
data = open(p, "rb").read()
assert data.count(b"</footer>") == 1, "footer count != 1"
idx = data.rfind(b"</footer>")

# 去重：正文前 80 字节已存在则跳过
already = []
new_blocks = []
for blk in blocks:
    head80 = blk[:80]
    if head80 in data:
        already.append(blk)
    else:
        new_blocks.append(blk)

new_insert = b"".join(new_blocks) + (b"\r\n" if new_blocks else b"")
new_data = data[:idx] + new_insert + data[idx:]
open(p, "wb").write(new_data)

# ---- 3. docs 镜像 ----
shutil.copyfile(p, f"{SEED_DIR}/docs/seed.html")

# ---- 4. 公众号弹药库标记 ·R156（B类 #11-#15，尾标记 ·R153，行尾追加）----
raw = open(AMMO, "rb").read()
txt = raw.decode("utf-8")
# 只对行尾的 ·R153 追加 ·R156（5 条 B类续行）
txt2 = re.sub(r"·R153(\r?\n|$)", r"·R153·R156\1", txt)
assert txt2.count("·R153·R156") == 5, f"marked {txt2.count('·R153·R156')} != 5"
open(AMMO, "wb").write(txt2.encode("utf-8"))

# ---- 5. 核验 ----
final = open(p, "rb").read()
